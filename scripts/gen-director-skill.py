#!/usr/bin/env python3
"""Generates the skill texts Duo installs from the Markdown sources under skills/.

- skills/duo-director/SKILL.md -> Sources/DuoControl/DirectorSkillText.swift (`DirectorSkill.source`),
  plus every skills/duo-director/reference/*.md as `DirectorSkill.references` (progressive disclosure).
- skills/duo-worker/SKILL.md   -> Sources/DuoControl/WorkerSkillText.swift (`WorkerSkill.source`).

The Markdown files are the sources of the shared director skill (DL-193) and the worker skill; Duo
installs the generated text. Run after editing the Markdown; DuoChecks fails when the two differ.
Never edit the Swift files by hand.
"""
import pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent


def literal(text, where):
    if '"""#' in text:
        sys.exit(f"{where} contains the raw-string terminator")
    return '#"""\n' + text + '\n"""#'  # a raw literal drops the line break before its closing delimiter


def emit(out, swift):
    if out.exists() and out.read_text() == swift:
        print(f"{out.name}: unchanged")
    else:
        out.write_text(swift)
        print(f"{out.name}: written")


d = root / "skills/duo-director"
refs = sorted((d / "reference").glob("*.md")) if (d / "reference").is_dir() else []
swift = (
    "// Generated by scripts/gen-director-skill.py from skills/duo-director/SKILL.md and skills/duo-director/reference/*.md. Don't edit.\n\n"
    "extension DirectorSkill {\n"
    "    /// The skill's source text, with `{{FORMAT}}` where the installer writes its format.\n"
    "    static let source = " + literal((d / "SKILL.md").read_text(), "SKILL.md") + "\n\n"
    "    /// Files the skill loads on demand (`reference/<name>.md`), by relative path.\n"
    "    static let references: [(name: String, text: String)] = [\n"
)
for r in refs:
    swift += f'        (name: "reference/{r.name}", text: ' + literal(r.read_text(), r.name) + "),\n"
swift += "    ]\n}\n"
emit(root / "Sources/DuoControl/DirectorSkillText.swift", swift)

w = root / "skills/duo-worker/SKILL.md"
swift = (
    "// Generated by scripts/gen-director-skill.py from skills/duo-worker/SKILL.md. Don't edit.\n\n"
    "extension WorkerSkill {\n"
    "    /// The skill's source text, with `{{FORMAT}}` and `{{REVISION}}` where the installer writes them.\n"
    "    static let source = " + literal(w.read_text(), "worker SKILL.md") + "\n"
    "}\n"
)
emit(root / "Sources/DuoControl/WorkerSkillText.swift", swift)
