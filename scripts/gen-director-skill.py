#!/usr/bin/env python3
"""Generates Sources/DuoControl/DirectorSkillText.swift from skills/duo-director/SKILL.md.

The Markdown file is the source of the shared director skill (DL-193); Duo installs the generated
text as the user's `duo-director` skill. Run after editing the Markdown; DuoChecks fails when the
two differ. Never edit the Swift file by hand.
"""
import pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "skills/duo-director/SKILL.md"
out = root / "Sources/DuoControl/DirectorSkillText.swift"

text = src.read_text()
if '"""#' in text:
    sys.exit("SKILL.md contains the raw-string terminator")
swift = (
    "// Generated by scripts/gen-director-skill.py from skills/duo-director/SKILL.md. Don't edit.\n\n"
    "extension DirectorSkill {\n"
    "    /// The skill's source text, with `{{FORMAT}}` where the installer writes its format.\n"
    '    static let source = #"""\n'
    + text
    + '\n"""#\n'  # a raw literal drops the line break before its closing delimiter
    "}\n"
)
if out.exists() and out.read_text() == swift:
    print("DirectorSkillText.swift: unchanged")
else:
    out.write_text(swift)
    print("DirectorSkillText.swift: written")
