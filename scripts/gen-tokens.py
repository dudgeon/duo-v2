    if name.startswith("$"):
        continue
    d = dark.get(name, {}).get("value", spec["value"])
    use = spec.get("use", "")
    w(f"    /// {use}" if use else f"    /// {name}")
    w(f"    public static let {name} = Color(nsColor: NSColor.duoDynamic(light: {hex6(spec['value'])}, dark: {hex6(d)}, name: \"{name}\"{alphas(name, spec)}))")
