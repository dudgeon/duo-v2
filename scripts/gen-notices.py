#!/usr/bin/env python3
"""Generate THIRD-PARTY-NOTICES.md from Vendor/, SwiftTerm's checkout and the search model's card (C-82).

bundle.sh copies the result into the app's Resources. Run after changing a vendored component or the
SwiftTerm pin:  python3 scripts/gen-notices.py   (needs `swift package resolve` for SwiftTerm's LICENSE).
Not shipped: swift-markdown-engine (in Vendor/, linked by nothing), SwiftTerm's own tool-only
dependencies (swift-argument-parser, swift-png, h: the Termcast target and non-macOS traits), and the
video pipeline.
"""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
out = root / "THIRD-PARTY-NOTICES.md"


def read(rel):
    p = root / rel
    if not p.exists():
        sys.exit(f"gen-notices: missing {rel}" + (" (run `swift package resolve`)" if ".build" in rel else ""))
    return p.read_text(encoding="utf-8").strip()


def swiftterm_license():
    for base in [root, *root.parents]:
        p = base / ".build/checkouts/SwiftTerm/LICENSE"
        if p.exists():
            return p.read_text(encoding="utf-8").strip()
    sys.exit("gen-notices: SwiftTerm's LICENSE not found under .build/checkouts (run `swift package resolve`)")


def fence(text):
    return "\n```text\n" + text + "\n```\n"


model = json.loads(read("Models/bge-small-fp16/PROVENANCE.json"))
card = read("Models/bge-small-fp16/MODEL_CARD.md")
if "license: mit" not in card:
    sys.exit("gen-notices: the model card no longer says license: mit; re-check the model's licence")

mit_bge = """MIT License

Copyright (c) Beijing Academy of Artificial Intelligence (BAAI), FlagEmbedding

Permission is hereby granted, free of charge, to any person obtaining a copy of this software and
associated documentation files (the "Software"), to deal in the Software without restriction, including
without limitation the rights to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is furnished to do so, subject to the
following conditions:

The above copyright notice and this permission notice shall be included in all copies or substantial
portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT NOT
LIMITED TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO
EVENT SHALL THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER
IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE
USE OR OTHER DEALINGS IN THE SOFTWARE."""

cm = read("Vendor/codemirror/dist/THIRD-PARTY-LICENSES.md").split("\n", 1)[1].strip()
cm = cm.replace("\n## ", "\n#### ").replace("## @", "#### @", 1)

parts = [
    "# Third-party notices\n",
    "Duo includes the software below. Each component keeps its own licence; the notices are reproduced as "
    "those licences require. This file is generated by `scripts/gen-notices.py` and ships in the app's Resources.\n",
    "| Component | Licence | Used for |\n|---|---|---|\n"
    "| SwiftTerm | MIT | the terminal |\n"
    "| Sparkle 2.10.0 | MIT (with bundled externals) | in-app updates |\n"
    "| CodeMirror 6 and Lezer | MIT | the document editor |\n"
    "| @aiden0z/pptx-renderer 1.3.0 | Apache-2.0; bundles ECharts (Apache-2.0), JSZip (MIT), mtx-decompressor (MPL-2.0) | the PowerPoint viewer |\n"
    "| @file-viewer/docx 0.3.33 | Apache-2.0 | the Word viewer |\n"
    "| JSZip 3.10.1 | MIT | the Word viewer |\n"
    f"| {model['model']} (Core ML fp16) | MIT | cross-project search |\n",
    "## SwiftTerm (MIT)\n" + fence(swiftterm_license()),
    "## Sparkle 2.10.0 (MIT, with bundled externals)\n" + fence(read("Vendor/Sparkle/LICENSE")),
    "## CodeMirror 6 and Lezer (MIT)\n\nThe licence of each package bundled into the editor:\n\n" + cm + "\n",
    "## @aiden0z/pptx-renderer 1.3.0 (Apache-2.0)\n\n" + read("Vendor/pptx-renderer/THIRD_PARTY_NOTICES.md").split("\n", 1)[1].strip()
    + "\n\nThe bundle also contains Apache ECharts (Apache-2.0, covered by the licence below) and JSZip (MIT, below under the Word viewer).\n"
    + fence(read("Vendor/pptx-renderer/LICENSE")),
    "### mtx-decompressor 1.4.2 (MPL-2.0)\n" + fence(read("Vendor/pptx-renderer/licenses/mtx-decompressor-MPL-2.0.txt")),
    "### ECMA-376 notice\n" + fence(read("Vendor/pptx-renderer/licenses/ECMA-text-copyright-notice.txt")),
    "## @file-viewer/docx 0.3.33 (Apache-2.0)\n\n" + read("Vendor/docx-viewer/NOTICE") + "\n" + fence(read("Vendor/docx-viewer/LICENSE")),
    "## JSZip 3.10.1 (MIT or GPLv3; used under MIT)\n\n" + "```text\n" + read("Vendor/docx-viewer/LICENSE-jszip.md").split("GPL version 3")[0].strip() + "\n```\n",
    f"## {model['model']} (MIT)\n\nThe search model is BAAI's bge-small-en-v1.5 (revision `{model['revision'][:8]}`), "
    "converted to Core ML fp16 by Duo. Its model card declares the MIT licence.\n" + fence(mit_bge),
]
out.write_text("\n".join(parts).rstrip() + "\n", encoding="utf-8")
print(f"wrote {out.relative_to(root)} ({out.stat().st_size} bytes)")
